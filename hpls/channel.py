"""Physical-layer channel simulator.

Model
-----
A tapped-delay-line (TDL) multipath channel with the normalised delay/power
profiles of 3GPP TR 38.901 (TDL-A/B/C).  Each tap is a Rayleigh process
generated by a sum-of-sinusoids (Jakes/Clarke) generator with uniform
angle-of-arrival, so the temporal autocorrelation of every tap follows
``J_0(2*pi*f_d*dt)`` and the coherence time is ``0.423/f_d``.

The channel frequency response (CFR) seen at OFDM subcarrier ``f`` and time
``t`` is

    H(t, f) = sum_l a_l(t) * exp(-j*2*pi*f*tau_l).

Reciprocity and its imperfections
---------------------------------
Uplink and downlink share the *same* propagation realisation ``H(t,f)``
(TDD reciprocity), but the two nodes do not observe it identically:

1.  each node adds independent receiver noise at its own SNR;
2.  each node has a static transceiver gain error (scalar + per-subcarrier),
    modelling imperfect RF calibration;
3.  the two soundings are separated by ``tdd_gap_us``, so the channel has
    aged by that amount between the two observations.

Eavesdropper
------------
Eve observes a spatially correlated version of the legitimate CFR,
``H_E = rho*H + sqrt(1-rho^2)*H_ind``, where ``H_ind`` is an independent
realisation of the same TDL profile.  ``rho -> 1`` models an eavesdropper
inside the coherence volume of the legitimate link (worst case).
"""

