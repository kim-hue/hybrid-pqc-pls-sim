class TDLChannel:
    """One Rayleigh TDL propagation realisation, evaluable at any (t, f)."""

    def __init__(self, cfg: PhyConfig, rng: np.random.Generator,
                 profile: Optional[str] = None) -> None:
        name = profile or cfg.tdl_profile
        norm_delay, power_db = TDL_PROFILES[name]
        self.tau_s = norm_delay * cfg.delay_spread_ns * 1e-9
        p_lin = 10.0 ** (power_db / 10.0)
        self.p_lin = p_lin / p_lin.sum()          # unit total power
        self.n_taps = len(self.tau_s)
        self.fd_hz = cfg.doppler_hz()
        m = cfg.n_sinusoids
        # sum-of-sinusoids parameters: uniform AoA + uniform phase per tap
        self.aoa = rng.uniform(-np.pi, np.pi, size=(self.n_taps, m))
        self.phase = rng.uniform(-np.pi, np.pi, size=(self.n_taps, m))
        self.m = m

    def tap_gains(self, t_s: np.ndarray) -> np.ndarray:
        """Complex tap gains, shape ``(len(t), n_taps)``."""
        t = np.asarray(t_s, dtype=float)[:, None, None]                # (T,1,1)
        arg = 2.0 * np.pi * self.fd_hz * t * np.cos(self.aoa)[None] + self.phase[None]
        # (T, L, M) -> normalised complex Gaussian per tap
        g = np.exp(1j * arg).sum(axis=2) / np.sqrt(self.m)
        return g * np.sqrt(self.p_lin)[None, :]

    def cfr(self, t_s: np.ndarray, f_hz: np.ndarray) -> np.ndarray:
        """Channel frequency response, shape ``(len(t), len(f))``."""
        g = self.tap_gains(t_s)                                        # (T,L)
        steer = np.exp(-2j * np.pi * np.asarray(f_hz)[:, None] * self.tau_s[None, :])
        return g @ steer.T                                             # (T,F)


@dataclass
class Transceiver:
    """Static hardware imperfections of one radio front-end."""

    gain_lin: float
    per_sc_gain_lin: np.ndarray
    snr_db: float

    @staticmethod
    def sample(cfg: PhyConfig, n_pilots: int, rng: np.random.Generator,
               snr_db: Optional[float] = None) -> "Transceiver":
        g_db = rng.normal(0.0, cfg.gain_mismatch_db)
        sc_db = rng.normal(0.0, cfg.freq_mismatch_db, size=n_pilots)
        return Transceiver(10.0 ** (g_db / 20.0), 10.0 ** (sc_db / 20.0),
                           cfg.snr_db if snr_db is None else snr_db)


class RadioWorld:
    """The shared radio environment for one session (UE, gNB and Eve)."""

    def __init__(self, cfg: PhyConfig, seed: Optional[int] = None,
                 rng: Optional[np.random.Generator] = None) -> None:
        self.cfg = cfg
        self.rng = rng if rng is not None else np.random.default_rng(seed)
        # legitimate reciprocal propagation channel + an independent one for Eve
        self.ch = TDLChannel(cfg, self.rng)
        self.ch_eve = TDLChannel(cfg, self.rng)
        self._tx: Dict[str, Transceiver] = {}

    def transceiver(self, role: str, n_pilots: int) -> Transceiver:
        if role not in self._tx:
            snr = self.cfg.eve_snr_db if role == "E" else self.cfg.snr_db
            self._tx[role] = Transceiver.sample(self.cfg, n_pilots, self.rng, snr)
        return self._tx[role]

    def observe(self, role: str, t_s: np.ndarray, f_hz: np.ndarray) -> np.ndarray:
        """Noisy CFR measurement of ``role`` in {'U', 'B', 'E'}."""
        n_pilots = len(f_hz)
        tx = self.transceiver(role, n_pilots)
        h = self.ch.cfr(t_s, f_hz)
        if role == "E":
            rho = float(np.clip(self.cfg.eve_csi_correlation, 0.0, 1.0))
            h = rho * h + np.sqrt(max(0.0, 1.0 - rho ** 2)) * self.ch_eve.cfr(t_s, f_hz)
        h = h * tx.gain_lin * tx.per_sc_gain_lin[None, :]
        # additive receiver noise at the node's operating SNR
        sigma2 = float(np.mean(np.abs(h) ** 2)) / (10.0 ** (tx.snr_db / 10.0))
        noise = np.sqrt(sigma2 / 2.0) * (self.rng.standard_normal(h.shape)
                                         + 1j * self.rng.standard_normal(h.shape))
        return h + noise

    def noise_floor(self, role: str, n_pilots: int) -> float:
        """Noise variance the node knows from its own AGC/thermal calibration."""
        tx = self.transceiver(role, n_pilots)
        return 10.0 ** (-tx.snr_db / 10.0)
